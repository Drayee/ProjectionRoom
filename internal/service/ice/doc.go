// Package ice 只负责一件事：决定「此刻该把哪些 ICE 条目下发给浏览器」，以及它们还能用多久。
//
// 流程是固定的四步：
//
//	服务端 UDP 探测（RFC 5389 Binding Request）
//	  → 打分（RTT 8 成 + 跨窗口成功率 2 成）
//	  → 加权轮询选出不超过 MaxSTUN 条（粘性条目优先占位）
//	  → 连同 TTL 一起下发（/api/ice 与 POST /api/rooms）
//
// 为什么要有这个包：TURN 已彻底退役（原因与重新引入的条件见 README「为什么不再有 TURN」），
// 于是浏览器拿到的每一个 ICE 条目都必须是此刻真的能用的 STUN。而默认列表里既有实测 11ms 的
// 国内节点，也有一条实测 4 秒无响应的服务器。把整份列表原样丢给浏览器等于让它自己踩雷：
// 候选收集阶段任何一次无响应都会拖慢甚至打断 srflx 候选的收集，直接表现为"房间进了但连不上"。
// 因此把"谁可用"的判断搬到服务端：用服务端到 STUN 的实测 RTT 与跨窗口成功率排序，只下发前 N 条。
//
// 边界（必须知道，否则会误读分数）：
//   - 探测从**服务端**发起，衡量的是"服务端 → STUN"的可达性，不是"观众 → STUN"。
//     默认列表全是公网节点，对同一条互联网主干上的两端，这两个量高度相关；这也是 60s 周期
//     的意义——路径一变，一个窗口内就会重新排序。
//   - 探测只测 IPv4 路径（见 UDPProber 的注释）；下发的 URL 原样保留，IPv6 由浏览器自己走。
//   - 探测失败不会让下发列表变空：见 Registry.Payload 的降级说明。
