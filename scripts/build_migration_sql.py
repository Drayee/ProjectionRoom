#!/usr/bin/env python3
"""
yachiyo -> ProjectionRoom 真正的字段映射导入器

读取本地 yachiyo，做字段映射与清洗，产出可直接灌入 projectionroom 的 SQL。

映射规则：
  users.user_id      -> users.id
  users.name         -> users.username (lower + 去冲突) & users.display_name
  users.email        -> users.email
  users.role         -> users.role ('normal'/'member' -> 'user')
  users.password     -> users.password_hash (MD5 32hex 直携，登录时自动升级 bcrypt)
  users.create_time  -> users.created_at (原值是 TIME 类型，只有时分秒 -> 用固定基准日期)

  posting.id         -> posts.id
  posting.user_id    -> posts.author_id
  posting.title      -> posts.title (截断 60 字符)
  posting.content    -> posts.content
  posting.score      -> posts.like_count

用法:
  python scripts/build_migration_sql.py --out _migrate/dump/mapped.sql
"""

import argparse
import os
import sys
from datetime import datetime

import psycopg2

OLD = dict(host='localhost', database='yachiyo', user='postgres',
           password='yuanshen123', port=5432)

# yachiyo 的 create_time 是 TIME 类型（只有时分秒），给一个基准日期让数据看起来合理
BASE_DATE = datetime(2024, 1, 1)


def sql_lit(v):
    """生成安全的 SQL 字面量"""
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'TRUE' if v else 'FALSE'
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v).replace("'", "''")
    return f"'{s}'"


def build_username_map(rows):
    """为每个用户生成唯一且合法的 username"""
    taken = set()
    result = {}
    for uid, name in rows:
        base = (name or '').strip().lower()
        if not base:
            base = f'user_{uid}'
        # varchar(20) 按字符计
        base = base[:20]
        cand = base
        n = 1
        while cand in taken:
            suffix = f'_{n}'
            cand = (base[:20 - len(suffix)]) + suffix
            n += 1
        taken.add(cand)
        result[uid] = cand
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='_migrate/dump/mapped.sql')
    args = ap.parse_args()

    conn = psycopg2.connect(**OLD)
    cur = conn.cursor()

    # ---------- users ----------
    cur.execute("SELECT user_id, name, email, role, password FROM users ORDER BY user_id")
    urows = cur.fetchall()
    umap = build_username_map([(r[0], r[1]) for r in urows])

    lines = []
    lines.append('-- Generated by build_migration_sql.py')
    lines.append(f'-- {datetime.now().isoformat()}')
    lines.append('BEGIN;')
    lines.append('')

    lines.append('-- ===== users =====')
    lines.append('TRUNCATE users, sessions, posts, post_comments, post_likes '
                 'RESTART IDENTITY CASCADE;')
    lines.append('')

    ok_users = 0
    for uid, name, email, role, pwd in urows:
        username = umap[uid]
        display = (name or '').strip() or username
        display = display[:32]
        new_role = 'admin' if (role or '').lower() in ('admin',) else 'user'
        email_v = (email or '').strip().lower() or None
        # MD5 直携；若为空则给一个不可能匹配的占位（登录会失败，但不破坏约束）
        pwd_v = (pwd or '').strip()
        if not pwd_v:
            pwd_v = '0' * 32
        ts = sql_lit(BASE_DATE.isoformat())
        lines.append(
            'INSERT INTO users (id, username, display_name, password_hash, email, '
            'role, status, token_version, created_at, updated_at, last_seen_at) '
            f'VALUES ({uid}, {sql_lit(username)}, {sql_lit(display)}, {sql_lit(pwd_v)}, '
            f'{sql_lit(email_v)}, {sql_lit(new_role)}, \'active\', 1, {ts}, {ts}, {ts}) '
            'ON CONFLICT (id) DO NOTHING;'
        )
        ok_users += 1
    lines.append('')

    # ---------- posts ----------
    cur.execute("""
        SELECT id, user_id, title, content, score
        FROM posting
        WHERE user_id IN (SELECT user_id FROM users)
        ORDER BY id
    """)
    prows = cur.fetchall()

    lines.append('-- ===== posts =====')
    ok_posts = 0
    for pid, uid, title, content, score in prows:
        t = (title or '').strip()[:60]
        if not t:
            t = f'(无标题 {pid})'
        c = (content or '').strip()
        if not c:
            c = '(原文无内容)'
        like = int(score) if score else 0
        ts = sql_lit(BASE_DATE.isoformat())
        lines.append(
            'INSERT INTO posts (id, author_id, title, content, images, like_count, '
            'comment_count, created_at, updated_at) '
            f'VALUES ({pid}, {uid}, {sql_lit(t)}, {sql_lit(c)}, \'[]\'::jsonb, {like}, 0, {ts}, {ts}) '
            'ON CONFLICT (id) DO NOTHING;'
        )
        ok_posts += 1
    lines.append('')

    # ---------- 序列对齐 ----------
    lines.append('-- ===== reset sequences =====')
    lines.append("SELECT setval(pg_get_serial_sequence('users','id'), "
                 "COALESCE((SELECT MAX(id) FROM users), 1), true);")
    lines.append("SELECT setval(pg_get_serial_sequence('posts','id'), "
                 "COALESCE((SELECT MAX(id) FROM posts), 1), true);")
    lines.append('')
    lines.append('COMMIT;')

    cur.close()
    conn.close()

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

    size = os.path.getsize(args.out)
    print(f'[OK] users={ok_users} posts={ok_posts}')
    print(f'[OK] wrote {args.out} ({size:,} bytes)')


if __name__ == '__main__':
    main()
